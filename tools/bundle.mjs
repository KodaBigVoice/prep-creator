// Builds dist/prep.js: KaTeX and all of src/ in ONE classic script, so the prep creator is a single request.
// (Over a school web filter the ~200 separate module files of src/ can fail to load, which leaves a blank page.)
// Run: npm run build   (a test fails if dist/prep.js is older than the source)
import { build } from 'esbuild';
import fs from 'fs';
const katex = fs.readFileSync(new URL('../vendor/katex/katex.min.js', import.meta.url), 'utf8');
export async function bundle() {
  const r = await build({ entryPoints: [new URL('../src/ui/app.js', import.meta.url).pathname], bundle: true, format: 'iife', minify: true, target: 'es2020', write: false, legalComments: 'none' });
  return '/* PMU prep creator: generated by tools/bundle.mjs from src/ and vendor/katex. Do not edit; run npm run build. */\n' + katex + '\n;' + r.outputFiles[0].text;
}
if (process.argv[1] && process.argv[1].endsWith('bundle.mjs')) {
  const out = await bundle();
  fs.mkdirSync(new URL('../dist/', import.meta.url), { recursive: true });
  fs.writeFileSync(new URL('../dist/prep.js', import.meta.url), out);
  console.log(`dist/prep.js: ${(out.length / 1024).toFixed(0)} KB`);
}
