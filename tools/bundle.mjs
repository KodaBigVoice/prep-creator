// Builds prep.html from src/prep.template.html with EVERYTHING inline: the stylesheets (KaTeX with its fonts inlined, sheet.css, app.css), KaTeX and all of src/ in ONE inline script,
// so the prep creator is a single page that arrives whole or not at all, like BarModel and TopHeavy. (On some school devices separate
// script, stylesheet and font files failed to load while pages themselves loaded: blank pages, "A file did not load", the wrong maths font.)
// Run: npm run build   (a test fails if prep.html is older than its source)
import { build } from 'esbuild';
import fs from 'fs';
const at = (p) => new URL('../' + p, import.meta.url);
const read = (p) => fs.readFileSync(at(p), 'utf8');

// KaTeX's stylesheet with its fonts written into it (base64), so the maths fonts cannot be blocked or fail as separate downloads
function katexCss() {
  return read('vendor/katex/katex.min.css').replace(/url\((fonts\/[^)]+\.woff2)\)/g, (_, f) => `url(data:font/woff2;base64,${fs.readFileSync(at('vendor/katex/' + f)).toString('base64')})`);
}
// the page's own CSS lives in css/ and refers to ../fonts/; it is injected into the page itself, so those paths are made relative to the page
const pageCss = (f) => read(f).replace(/url\(\.\.\//g, 'url(');
const cssInjector = () => `(function(){var s=document.createElement('style');s.textContent=${JSON.stringify([katexCss(), pageCss('css/sheet.css'), pageCss('css/app.css')].join('\n'))};(document.head||document.documentElement).appendChild(s)})();\n`;

export async function bundle() {
  const r = await build({ entryPoints: [at('src/ui/app.js').pathname], bundle: true, format: 'iife', minify: true, target: 'es2020', write: false, legalComments: 'none' });
  return cssInjector() + read('vendor/katex/katex.min.js') + '\n;' + r.outputFiles[0].text;
}
// the whole page: the template with the bundle inlined (a </script or <!-- inside the code must not end or confuse the inline script)
export async function page() {
  const code = (await bundle()).replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
  const tpl = read('src/prep.template.html');
  if (!tpl.includes('<!--PMU-BUNDLE-->')) throw new Error('template has no <!--PMU-BUNDLE--> marker');
  return tpl.replace('<!--PMU-BUNDLE-->', () => '<script>\n/* PMU prep creator: generated by tools/bundle.mjs from src/, css/ and vendor/katex. Do not edit: run npm run build. */\n' + code + '\n</script>');
}
if (process.argv[1] && process.argv[1].endsWith('bundle.mjs')) {
  const out = await page();
  fs.writeFileSync(at('prep.html'), out);
  console.log(`prep.html: ${(out.length / 1024).toFixed(0)} KB`);
}
