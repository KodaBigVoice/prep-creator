// Builds dist/prep.js: the stylesheets (KaTeX with its fonts inlined, sheet.css, app.css), KaTeX and all of src/ in ONE classic script,
// so the prep creator is a single request that either arrives whole or not at all. (Over a school web filter ~200 module files, and
// then separate stylesheets and font files, failed to load: blank pages, "A file did not load", the maths in the wrong font.)
// Run: npm run build   (a test fails if dist/prep.js is older than the source)
import { build } from 'esbuild';
import fs from 'fs';
const at = (p) => new URL('../' + p, import.meta.url);
const read = (p) => fs.readFileSync(at(p), 'utf8');

// KaTeX's stylesheet with its fonts written into it (base64), so the maths fonts cannot be blocked or fail as separate downloads
function katexCss() {
  return read('vendor/katex/katex.min.css').replace(/url\((fonts\/[^)]+\.woff2)\)/g, (_, f) => `url(data:font/woff2;base64,${fs.readFileSync(at('vendor/katex/' + f)).toString('base64')})`);
}
// the page's own CSS lives in css/ and refers to ../fonts/; it is injected into the page itself, so those paths are made relative to the page
const pageCss = (f) => read(f).replace(/url\(\.\.\//g, 'url(');
const cssInjector = () => `(function(){var s=document.createElement('style');s.textContent=${JSON.stringify([katexCss(), pageCss('css/sheet.css'), pageCss('css/app.css')].join('\n'))};(document.head||document.documentElement).appendChild(s)})();\n`;

export async function bundle() {
  const r = await build({ entryPoints: [at('src/ui/app.js').pathname], bundle: true, format: 'iife', minify: true, target: 'es2020', write: false, legalComments: 'none' });
  return '/* PMU prep creator: generated by tools/bundle.mjs from src/, css/ and vendor/katex. Do not edit; run npm run build. */\n' + cssInjector() + read('vendor/katex/katex.min.js') + '\n;' + r.outputFiles[0].text;
}
if (process.argv[1] && process.argv[1].endsWith('bundle.mjs')) {
  const out = await bundle();
  fs.mkdirSync(at('dist/'), { recursive: true });
  fs.writeFileSync(at('dist/prep.js'), out);
  console.log(`dist/prep.js: ${(out.length / 1024).toFixed(0)} KB`);
}
